export function getGame(slug: string): GameMeta {
  const g = GAMES.find((x) => x.slug === slug);
  if (!g) throw new Error(`Unknown game: ${slug}`);
  return g;
}

/** Games in one category, home-hub order preserved. */
export function gamesInCategory(category: CategoryId): GameMeta[] {
  return GAMES.filter((g) => g.category === category);
}

/** Games pitched at one age band, home-hub order preserved. */
export function gamesInBand(ageBand: AgeBandId): GameMeta[] {
  return GAMES.filter((g) => g.ageBand === ageBand);
}
