// Single source of truth for every game. The home hub maps over this, and each
// game imports its own entry by slug for consistent titles/colors.
//
// Two browse axes live here alongside the display data: `category` (what the
// game teaches) and `ageBand` (who it is pitched at). Every category/band cell
// holds at least three games, so either axis can be filtered on its own or the
// two combined without ever landing on an empty grid.

