export type AgeBandId = (typeof AGE_BANDS)[number]["id"];

export type GameMeta = {
  slug: string;
  title: string;
  emoji: string;
  subject: string;
  /** Browse grouping on the home hub. */
  category: CategoryId;
  /** Which age band this game is pitched at. */
  ageBand: AgeBandId;
  blurb: string;
  /** Tailwind gradient classes for the card + in-game accent. */
  gradient: string;
  /** Solid accent used for buttons/borders inside the game. */
  accent: string;
  /** How the score is phrased on the home card, e.g. "pts" or "level". */
  scoreLabel: string;
};

